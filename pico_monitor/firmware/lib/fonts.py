def _glyph(table, ch):
    return table.get(ch) or table.get(ch.upper()) or table.get(" ")


def draw_tiny(fb, x, y, text, color=1):
    """3x5 text — units K/M/G, footer."""
    cx = x
    for ch in text:
        cols = _glyph(_TINY, ch)
        for dx, col in enumerate(cols):
            for dy in range(5):
                if col & (1 << dy):
                    fb.pixel(cx + dx, y + dy, color)
        cx += 4  # 3px + 1 gap
    return cx


def draw_normal(fb, x, y, text, color=1):
    """5x7 text — labels / header titles."""
    cx = x
    for ch in text:
        cols = _glyph(_NORMAL, ch)
        for dx, col in enumerate(cols):
            for dy in range(7):
                if col & (1 << dy):
                    fb.pixel(cx + dx, y + dy, color)
        cx += 6  # 5px + 1 gap
    return cx


def draw_big(fb, x, y, text, color=1):
    """Double-size 5x7 ≈ 10x14 bold numbers."""
    cx = x
    for ch in text:
        cols = _glyph(_NORMAL, ch)
        for dx, col in enumerate(cols):
            for dy in range(7):
                if col & (1 << dy):
                    px = cx + dx * 2
                    py = y + dy * 2
                    fb.fill_rect(px, py, 2, 2, color)
        cx += 11
    return cx


def text_width_tiny(text):
    return len(text) * 4


def text_width_normal(text):
    return len(text) * 6


def text_width_big(text):
    return len(text) * 11
