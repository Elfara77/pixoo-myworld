def _glyph(table: dict[str, tuple[int, ...]], ch: str) -> tuple[int, ...]:
    return table.get(ch) or table.get(ch.upper()) or table.get(" ") or (0, 0, 0, 0, 0)


def text_width_tiny(text: str) -> int:
    w = 0
    for ch in text:
        w += 2 if ch == "°" else 4
    return w


def text_ink_width_tiny(text: str) -> int:
    """Advance width minus the unused trailing column after the last 3×5 glyph.

    Tiny glyphs are 3px wide with a 4px advance; right-aligning by advance width
    leaves a dead black pixel on the edge. Degree (° ) already ends on ink.
    """
    w = text_width_tiny(text)
    if w <= 0:
        return 0
    if text[-1] == "°":
        return w
    return w - 1


def text_width_normal(text: str) -> int:
    return len(text) * 6


def text_width_big(text: str) -> int:
    return len(text) * 11


def _put(img, x: int, y: int, color: Sequence[int], w: int = 64, h: int = 64) -> None:
    if 0 <= x < w and 0 <= y < h:
        img.putpixel((x, y), tuple(color[:3]))


def draw_tiny(img, x: int, y: int, text: str, color: Sequence[int]) -> int:
    """3×5 text. Returns x after last glyph."""
    cx = x
    for ch in text:
        if ch == "°":
            # One bright pixel (superscript dot); narrow advance so °C reads clearly.
            _put(img, cx + 1, y, color)
            cx += 2
            continue
        cols = _glyph(_TINY, ch)
        for dx, col in enumerate(cols):
            for dy in range(5):
                if col & (1 << dy):
                    _put(img, cx + dx, y + dy, color)
        cx += 4
    return cx


def draw_normal(img, x: int, y: int, text: str, color: Sequence[int]) -> int:
    """5×7 text. Returns x after last glyph."""
    cx = x
    for ch in text:
        cols = _glyph(_NORMAL, ch)
        for dx, col in enumerate(cols):
            for dy in range(7):
                if col & (1 << dy):
                    _put(img, cx + dx, y + dy, color)
        cx += 6
    return cx


def draw_big(img, x: int, y: int, text: str, color: Sequence[int]) -> int:
    """Double-size 5×7 ≈ 10×14. Returns x after last glyph."""
    cx = x
    for ch in text:
        cols = _glyph(_NORMAL, ch)
        for dx, col in enumerate(cols):
            for dy in range(7):
                if col & (1 << dy):
                    px = cx + dx * 2
                    py = y + dy * 2
                    for oy in range(2):
                        for ox in range(2):
                            _put(img, px + ox, py + oy, color)
        cx += 11
    return cx


def draw_text(
    img,
    x: int,
    y: int,
    text: str,
    color: Sequence[int],
    *,
    size: str = "normal",
) -> int:
    if size == "tiny":
        return draw_tiny(img, x, y, text, color)
    if size == "big":
        return draw_big(img, x, y, text, color)
    return draw_normal(img, x, y, text, color)


def text_width(text: str, *, size: str = "normal") -> int:
    if size == "tiny":
        return text_width_tiny(text)
    if size == "big":
        return text_width_big(text)
    return text_width_normal(text)


def text_ink_width(text: str, *, size: str = "normal") -> int:
    """Width through the last lit column (for flush-right layout)."""
    if size == "tiny":
        return text_ink_width_tiny(text)
    return text_width(text, size=size)


def scroll_slice(
    text: str,
    max_chars: int,
    *,
    t: float | None = None,
    period: float = 0.35,
    enabled: bool = True,
) -> str:
    """Return a window of `text` that advances over time when too long."""
    if max_chars < 1:
        return ""
    if not enabled or len(text) <= max_chars:
        return text[:max_chars]
    # Pad so the scroll loops cleanly
    pad = "  "
    loop = text + pad
    import time as _time

    now = _time.monotonic() if t is None else t
    start = int(now / period) % len(loop)
    doubled = loop + loop
    return doubled[start : start + max_chars]
